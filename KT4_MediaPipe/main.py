import os  # Импортируем модуль для работы с файлами чтобы проверять наличие картинок на диске
import cv2  # Импортируем OpenCV для захвата кадров с камеры их изменения и вывода на экран
import numpy as np  # Импортируем NumPy для быстрых математических расчетов координат и расстояний
import mediapipe as mp  # Импортируем MediaPipe для автоматического нахождения 3D-точек лица

STAR_K = 2.0    # Множитель размера звезды: картинка звезды будет ровно в 2 раза больше ширины глаза
NOSE_K = 0.25   # Множитель размера носа: картинка клоунского носа займет 25% (четверть) от ширины лица


def load_png(path):  # Создаем функцию для правильной загрузки картинок на прозрачном фоне
    """Читает PNG и гарантирует 4 канала (BGRA)."""
    if not os.path.exists(path):  # Проверяем существует ли вообще файл по указанному пути
        return None  # Если файла нет возвращаем пустоту чтобы программа не сломалась

    img = cv2.imread(path, cv2.IMREAD_UNCHANGED)  # Загружаем картинку "как есть" сохраняя прозрачный слой
    if img is None:  # Проверяем удалось ли OpenCV успешно расшифровать файл изображения
        return None  # Если файл поврежден или пуст возвращаем пустоту

    if img.ndim == 2:  # Если картинка внезапно оказалась строго черно-белой (всего два измерения матрицы)
        img = cv2.cvtColor(img, cv2.COLOR_GRAY2BGRA)  # Преобразуем её в цветной формат с альфа-каналом
    elif img.shape[2] == 3:  # Если картинка обычная цветная (BGR) но в ней нет слоя прозрачности
        img = cv2.cvtColor(img, cv2.COLOR_BGR2BGRA)  # Принудительно добавляем к ней четвертый альфа-канал

    # Находим все пиксели у которых цвета B, G, R очень яркие (больше 240) то есть практически чисто белый цвет
    white = np.all(img[:, :, :3] > 240, axis=2)
    img[white, 3] = 0  # стираем белый фон у картинки
    return img  # Возвращаем готовую картинку с правильной прозрачностью
        


def overlay_image(bg, ov, cx, cy, size):  # Функция наложения прозрачной маски (ov) на кадр с веб-камеры (bg)
    """Накладывает ov (BGRA) квадратом size x size с центром в (cx, cy).
    Если выходит за кадр обрезается, а не пропадает."""
    size = max(int(size), 2)  # Убеждаемся, что размер маски не меньше двух пикселей, чтобы не было ошибок сжатия
    ov = cv2.resize(ov, (size, size))  # Подгоняем картинку маски под рассчитанный квадратный размер (size на size)
    x1, y1 = cx - size // 2, cy - size // 2  # Рассчитываем левую верхнюю точку кадра, где должна начаться маска
    x2, y2 = x1 + size, y1 + size  # Рассчитываем правую нижнюю точку кадра, где маска должна закончиться

    bx1, by1 = max(x1, 0), max(y1, 0)  # Срезаем левую/верхнюю координату до 0 если маска частично вылезла за левый край
    bx2, by2 = min(x2, bg.shape[1]), min(y2, bg.shape[0])  # Срезаем правую/нижнюю координату по краям экрана веб-камеры
    if bx1 >= bx2 or by1 >= by2:  # Если маска полностью оказалась за пределами видимости экрана
        return  # Завершаем функцию раньше времени и ничего не рисуем чтобы избежать сбоя

    ov = ov[by1 - y1:by2 - y1, bx1 - x1:bx2 - x1]  # Обрезаем саму картинку маски оставляя только ту часть что влезла в кадр
    alpha = ov[:, :, 3:4] / 255.0  # Вытаскиваем слой прозрачности маски и превращаем диапазон 0-255 в удобные доли от 0.0 до 1.0
    roi = bg[by1:by2, bx1:bx2]  # Вырезаем кусочек живого кадра с веб камеры куда мы прямо сейчас наложим маску
    # Смешиваем пиксели кадра и маски с учетом прозрачности и преобразуем результат обратно в стандартный формат целых чисел
    bg[by1:by2, bx1:bx2] = (alpha * ov[:, :, :3] + (1 - alpha) * roi).astype(np.uint8)


def draw_red_nose(frame, cx, cy, size):  # Запасная функция на случай если файла clown_nose.png нет на компьютере
    """Запасной вариант если нет clown_nose.png: красный круг."""
    r = max(int(size // 2), 2)  # Вычисляем радиус круглого носа на основе переданного размера
    cv2.circle(frame, (cx, cy), r, (0, 0, 255), -1)  # Рисуем сплошной красный круг (цвет BGR: 0, 0, 255) на месте кончика носа
    cv2.circle(frame, (cx - r // 3, cy - r // 3), max(r // 4, 1), (255, 255, 255), -1)  # Рисуем маленький белый кружок для блика


def pt(landmarks, idx, w, h):  # Помощник для перевода относительных координат нейросети в реальные пиксели монитора
    lm = landmarks[idx]  # Достаем нужную нам точку лица по её уникальному номеру (индексу)
    return np.array([lm.x * w, lm.y * h])  # Умножаем относительные x и y на ширину и высоту кадра и возвращаем массив


star = load_png("star.png")  # Загружаем изображение звезды
clown_nose = load_png("clown_nose.png")  # Загружаем изображение клоунского носа
if star is None:  # если файл звезды так и не удалось загрузить
    raise SystemExit("Не найден star.png рядом с main.py")  # Принудительно выключаем скрипт и пишем причину в консоль

cap = cv2.VideoCapture(0)  # Включаем захват видео со стандартной веб-камеры вашего компьютера
mp_face_mesh = mp.solutions.face_mesh  # Подключаем готовый программный модуль сетки лица MediaPipe

with mp_face_mesh.FaceMesh(  # Запускаем распознаватель лица со следующими настройками:
    max_num_faces=1,  # Будем искать и отслеживать в кадре только одно лицо
    refine_landmarks=True,  # Включаем максимальную точность распознавания зон вокруг глаз губ и зрачков
    min_detection_confidence=0.5,  # Нейросеть должна быть уверена минимум на 50% что перед ней лицо для старта
    min_tracking_confidence=0.5,  # Нейросеть должна удерживать лицо с уверенностью не менее 50% на живом видео
) as face_mesh:  # Называем настроенный инструмент именем face_mesh

    while True:  # Запускаем бесконечный цикл обработки видеопотока в реальном времени
        ret, frame = cap.read()  # Запрашиваем новый кадр с камеры.
        if not ret:  # Если кадр прочитать не удалось (камеру выдернули из разъема)
            print("Не удалось открыть камеру")  # Печатаем сообщение о проблеме в терминал
            break  # Немедленно выходим из цикла обработки видео

        h, w = frame.shape[:2]  # Извлекаем текущие высоту и ширину полученного с веб-камеры кадра
        results = face_mesh.process(cv2.cvtColor(frame, cv2.COLOR_BGR2RGB))  # Меняем цвета кадра на RGB и отдаем нейросети на поиск лица

        if results.multi_face_landmarks:  # Если на текущем кадре нейросеть успешно увидела лицо
            lm = results.multi_face_landmarks[0].landmark  # Берем массив всех ключевых точек этого первого найденного лица

            # Объявляем функцию для вычисления центра глаза и расстояния между его уголками
            def eye_center_width(i_left, i_right, i_top, i_bottom):
                left, right = pt(lm, i_left, w, h), pt(lm, i_right, w, h)  # Переводим координаты крайнего левого и правого уголков глаза в пиксели
                top, bottom = pt(lm, i_top, w, h), pt(lm, i_bottom, w, h)  # Переводим координаты верхнего и нижнего века в пиксели
                center = ((left + right) / 2 + (top + bottom) / 2) / 2  # Высчитываем центральную координату глаза как среднее значение
                width = np.linalg.norm(left - right)  # Измеряем длину вектора между левым и правым уголком (ширину глаза)
                return center, width  # Передаем наружу вычисленный центр и ширину глаза

            eye_a, width_a = eye_center_width(33, 133, 159, 145)  # Запускаем расчет параметров для первого (левого) глаза по номерам его точек
            eye_b, width_b = eye_center_width(362, 263, 386, 374)  # Запускаем расчет параметров для второго (правого) глаза по номерам его точек

            # Рисуем звезду поверх левого глаза. Координаты X и Y центра округляем до целых чисел
            overlay_image(frame, star, int(eye_a[0]), int(eye_a[1]), width_a * STAR_K)
            # Рисуем звезду поверх правого глаза. Координаты X и Y центра округляем до целых чисел
            overlay_image(frame, star, int(eye_b[0]), int(eye_b[1]), width_b * STAR_K)

            # Вычисляем общую ширину лица как расстояние между краями левой и правой щеки (точки 234 и 454)
            face_w = np.linalg.norm(pt(lm, 234, w, h) - pt(lm, 454, w, h))
            nose = pt(lm, 1, w, h)  # Получаем пиксельные координаты кончика носа (точка с индексом 1 в MediaPipe)
            nose_size = face_w * NOSE_K  # Задаем размер носа в пикселях на базе ширины лица и коэффициента (25%)
            if clown_nose is not None:  # Если картинка клоунского носа была успешно загружена на старте
                # Накладываем красивый PNG-рисунок клоунского носа точно по центру кончика носа
                overlay_image(frame, clown_nose, int(nose[0]), int(nose[1]), nose_size)
            else:  # Если файла с красивой маской носа на диске не оказалось
                # Вызываем нашу запасную функцию и рисуем обычный круг средствами кода OpenCV
                draw_red_nose(frame, int(nose[0]), int(nose[1]), nose_size)

        cv2.imshow("KT4 - MediaPipe", frame)  # Показываем текущий обработанный кадр в окне операционной системы
        if cv2.waitKey(1) & 0xFF == ord("q"):  # Ждем 1 миллисекунду. Если за это время пользователь нажал клавишу 'q'
            break  # Завершаем бесконечный цикл и закрываем программу

cap.release()  # Выключаем веб-камеру чтобы освободить её для использования другими программами
cv2.destroyAllWindows()  # Уничтожаем все созданные скриптом графические окна на экране


